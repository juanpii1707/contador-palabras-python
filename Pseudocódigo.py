import math
#PSEUDOCÓDIGO: Es una forma de escribir algoritmos usando un lenguaje informal y cercano al lenguaje humano, 
#              sin seguir sintaxis específicas de ningún lenguaje de programación particular.

#Practicas de Pseudocódigo 1:
#paso 1:
Ingresar_palabra = input("Ingrese una palabra: ")

#paso 2:
cantidad_letras = len(Ingresar_palabra)
#paso 3:
print("La cantidad de letras en la palabra es:", cantidad_letras)

#-------------------------------------------
#Practicas de Pseudocódigo 2:
#Paso 1:
radio = float(input("Ingrese el radio del círculo: "))

#Paso 2:
area = math.pi * radio ** 2

#Paso 3:
print("El área del círculo es:", area)

